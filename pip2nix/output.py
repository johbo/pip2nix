import os
import re
from operator import attrgetter

import pip2nix

from .models.package import indent


def write_output(path, packages, rendering):
    # Rendering prefetches sources and can fail. Do it before opening the
    # output file, so a failure leaves the previous one intact instead of
    # truncating it to an unparseable fragment.
    rendered_packages = render_packages(packages, rendering)

    with open(path, "w") as f:
        f.write(_about_comment())
        f.write("{ pkgs, fetchurl, fetchgit, fetchhg }:\n\n")
        f.write("self: super: {\n")
        f.write("  " + indent(2, rendered_packages))
        f.write("\n}\n")


def render_packages(packages, rendering):
    return "\n".join(
        f'"{pkg.name}" = {pkg.to_nix(rendering)}'
        for pkg in sorted(packages, key=attrgetter("name"))
    )


def read_repository_hashes(path):
    if not os.path.exists(path):
        return {}
    with open(path) as f:
        content = re.sub(r"\s+", " ", f.read())
    repositories = re.findall(
        r'url = "([^"]+)"; rev = "([^"]+)"; sha256 = "([^"]+)"', content
    )
    return {(url, rev): sha256 for url, rev, sha256 in repositories}


def _about_comment():
    # TODO: Collapse to one url once the fork merges back upstream
    return (
        f"# Generated by pip2nix {pip2nix.__version__}\n"
        + "# See https://github.com/johbo/pip2nix\n"
        + "# A fork of https://github.com/nix-community/pip2nix\n\n"
    )
